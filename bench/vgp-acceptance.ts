/**
 * Acceptance test of AGP export against the VGP post-curation scripts.
 *
 * The Vertebrate Genomes Project processes a PretextView AGP with
 * `split_agp` and its siblings (https://github.com/vgl-hub/vgl-curation, MIT;
 * the same code runs in the Galaxy post-curation workflow). `split_agp`
 * corrects the AGP to true sequence lengths, splits it by haplotype using
 * `Hap_1`/`Hap_2`, and moves `Unloc` and `Haplotig` rows, reading the tag in
 * the column straight after `Painted`.
 *
 * Two checks, each comparing what the scripts make of PretextView's AGP with
 * what they make of OpenPretext's rewrite of it (read into our model, written
 * by our writer):
 *
 *   A. The Galaxy tool's own test (tools-iuc, vgp_processcuration): the whole
 *      of `split_agp`, with its small FASTA. The fixture's objects are
 *      numbered from 33 and ours from 1, so object names are compared by
 *      order of appearance.
 *   B. A real VGP curation, king quail (test-data/case-study/quail): the
 *      haplotype split and the unloc/haplotig step, on 605 rows with `Hap_1`,
 *      `Hap_2`, `Unloc` and `Z` tags. The length correction is left out here
 *      because it needs the two 300 MB assembly FASTAs.
 *
 * The only line allowed to differ is the header's DESCRIPTION, which names
 * the program that wrote the file.
 *
 * Setup (once; test-data/ is not committed):
 *   git clone https://github.com/vgl-hub/vgl-curation test-data/vgl-curation
 *   cd test-data/vgl-curation && uv venv .venv && uv pip install --python .venv/bin/python .
 *   mkdir ../vgp-fixture   # and fetch tools/vgp_processcuration/test-data/* from galaxyproject/tools-iuc into it
 * Run:
 *   npx tsx bench/vgp-acceptance.ts
 */

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseAGP, planAGPImport } from '../src/formats/AGPParser';
import { readPretextHeader } from '../src/formats/PretextParser';
import { buildAGPObjects } from '../src/export/AGPModel';
import { buildAGPRows, formatAGPRow, generateAGPHeader } from '../src/export/AGPWriter';
import type { MapData } from '../src/core/State';
import { mapFromAGP, FILLER } from '../tests/helpers/agpFixtureMap';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const VENV = join(ROOT, 'test-data/vgl-curation/.venv/bin');
const FIXTURE = join(ROOT, 'test-data/vgp-fixture');
const QUAIL = join(ROOT, 'test-data/case-study/quail');

/** An AGP read into our model on `map` and written back by our writer. */
function rewrite(agpText: string, map?: MapData): string {
  const parsed = parseAGP(agpText);
  const onMap = map ?? mapFromAGP(parsed);
  const plan = planAGPImport(parsed, onMap);
  const contigs = plan.contigs.map((c) => ({ ...c }));
  plan.scaffolds.forEach((sc, k) => { for (const id of sc.contigIds) contigs[id].scaffoldId = k + 1; });
  const tags = new Map(plan.tags);
  const objects = buildAGPObjects({ ...onMap, contigs }, plan.contigOrder)
    .filter((o) => o.fragments.every((f) => f.component !== FILLER));
  const rows = buildAGPRows(objects, { tagsOf: (id) => tags.get(id) ?? [] }, 'pretextview').map(formatAGPRow);
  return [generateAGPHeader(onMap, 'pretextview'), ...rows].join('\n') + '\n';
}

function quailMap(): MapData {
  const bytes = readFileSync(join(QUAIL, 'bCotChi1.combined.pretext'));
  const { header, contigs } = readPretextHeader(
    bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength) as ArrayBuffer);
  return {
    filename: 'bCotChi1.combined.pretext', textureSize: header.numberOfPixels1D, numMipMaps: 1,
    tileResolution: header.textureResolution, tilesPerDimension: header.numberOfTextures1D,
    contigs: contigs.map((c, i) => ({
      name: c.name, originalIndex: i, length: c.length,
      pixelStart: c.pixelStart, pixelEnd: c.pixelEnd, inverted: false, scaffoldId: null,
    })),
    fileContigCount: contigs.length, genomeLength: Number(header.totalGenomeLength),
    contactMap: null, rawTiles: null, parsedHeader: null, extensions: new Map(),
  };
}

/**
 * Lines of a file, without the one that names the writing program, and
 * without trailing empty fields. PretextView leaves a stray tab at the end of
 * tagged rows, which the scripts carry through as empty columns; our rows end
 * at the last tag. The scripts read tags by position from the left, so the
 * empty columns on the right change nothing they do.
 */
function lines(path: string): string[] {
  return readFileSync(path, 'utf8').split('\n')
    .filter((l) => !/Generated by (PretextView|OpenPretext)/.test(l))
    .map((l) => l.replace(/[\t\r]+$/, ''));
}

/** Replace `Scaffold_<n>` object names with their order of first appearance. */
function byAppearance(rows: string[]): string[] {
  const seen = new Map<string, number>();
  return rows.map((l) => l.replace(/^Scaffold_\d+/, (m) => {
    if (!seen.has(m)) seen.set(m, seen.size + 1);
    return `Object_${seen.get(m)}`;
  }));
}

function firstDifference(a: string[], b: string[]): string | null {
  const n = Math.max(a.length, b.length);
  for (let i = 0; i < n; i++) {
    if (a[i] !== b[i]) return `line ${i + 1}\n      from PretextView's: ${JSON.stringify(a[i])}\n      from OpenPretext's: ${JSON.stringify(b[i])}`;
  }
  return null;
}

const OUTPUTS = ['Hap_1/hap1.agp', 'Hap_2/hap2.agp', 'Hap_1/hap.unlocs.no_hapdups.agp', 'Hap_2/hap.unlocs.no_hapdups.agp',
  'Hap_1/haplotigs.agp', 'Hap_2/haplotigs.agp'];

function main(): void {
  if (!existsSync(join(VENV, 'split_agp'))) {
    console.error('The VGP scripts are not set up under test-data/vgl-curation. See the setup lines at the top of this file.');
    process.exit(2);
  }
  const out = mkdtempSync(join(ROOT, 'test-data/vgp-acceptance-'));
  const failures: string[] = [];
  let ran = 0;

  // ---- A. The Galaxy tool's own test: the whole of split_agp ----
  if (existsSync(join(FIXTURE, 'test_input.agp'))) {
    ran++;
    const original = readFileSync(join(FIXTURE, 'test_input.agp'), 'utf8');
    const dirs = { theirs: join(out, 'galaxy-pretextview/'), ours: join(out, 'galaxy-openpretext/') };
    mkdirSync(dirs.theirs); mkdirSync(dirs.ours);
    writeFileSync(join(dirs.ours, 'input.agp'), rewrite(original));
    writeFileSync(join(dirs.theirs, 'input.agp'), original);
    for (const d of Object.values(dirs)) {
      execFileSync(join(VENV, 'split_agp'), ['-a', join(d, 'input.agp'), '-f', join(FIXTURE, 'test_input.fasta.gz'), '-o', d],
        { stdio: ['ignore', 'pipe', 'pipe'] });
    }
    // The scripts still do what the Galaxy test expects of them, on this machine.
    const expected: Array<[string, string]> = [
      ['corrected.agp', 'expected_corrected.agp'], ['Hap_1/hap1.agp', 'expected_hap1.agp'], ['Hap_2/hap2.agp', 'expected_hap2.agp'],
      ['Hap_1/hap.unlocs.no_hapdups.agp', 'expected_hap1_unlocs_no_hapdups.agp'],
      ['Hap_2/hap.unlocs.no_hapdups.agp', 'expected_hap2_unlocs_no_hapdups.agp'],
    ];
    for (const [made, want] of expected) {
      const d = firstDifference(lines(join(FIXTURE, want)), lines(join(dirs.theirs, made)));
      if (d) failures.push(`A, ${made}: the scripts no longer reproduce the Galaxy test's ${want} from PretextView's own file (${d})`);
    }
    for (const f of ['corrected.agp', ...OUTPUTS]) {
      const d = firstDifference(byAppearance(lines(join(dirs.theirs, f))), byAppearance(lines(join(dirs.ours, f))));
      if (d) failures.push(`A, ${f}: differs at ${d}`);
    }
    console.log(`A. Galaxy vgp_processcuration test: split_agp run on both files, ${OUTPUTS.length + 1} outputs compared`);
  } else {
    console.log('A. skipped: test-data/vgp-fixture/test_input.agp is not there');
  }

  // ---- B. King quail: haplotype split and unloc/haplotig handling ----
  const quailAgp = join(QUAIL, 'bCotChi1.combined.pretext.20240422.agp');
  if (existsSync(quailAgp) && existsSync(join(QUAIL, 'bCotChi1.combined.pretext'))) {
    ran++;
    const original = readFileSync(quailAgp, 'utf8');
    const dirs = { theirs: join(out, 'quail-pretextview/'), ours: join(out, 'quail-openpretext/') };
    mkdirSync(dirs.theirs); mkdirSync(dirs.ours);
    writeFileSync(join(dirs.theirs, 'input.agp'), original);
    writeFileSync(join(dirs.ours, 'input.agp'), rewrite(original, quailMap()));
    const steps = [
      // split_agp is installed as a script, not a module: load it from the checkout.
      'import sys',
      'sys.path.insert(0, sys.argv[2])',
      'import split_agp',
      'd = sys.argv[1]',
      "split_agp.hap_split(d + 'input.agp', d + 'Hap_1/hap1.agp', d + 'Hap_2/hap2.agp')",
      "split_agp.unloc(d + 'Hap_1/hap1.agp', d + 'Hap_1/')",
      "split_agp.unloc(d + 'Hap_2/hap2.agp', d + 'Hap_2/')",
    ].join('\n');
    for (const d of Object.values(dirs)) {
      execFileSync(join(VENV, 'python'), ['-c', steps, d, join(ROOT, 'test-data/vgl-curation/src')], { stdio: ['ignore', 'pipe', 'pipe'] });
    }
    let rows = 0;
    for (const f of OUTPUTS) {
      const theirs = lines(join(dirs.theirs, f));
      rows += theirs.length;
      const d = firstDifference(theirs, lines(join(dirs.ours, f)));
      if (d) failures.push(`B, ${f}: differs at ${d}`);
    }
    const count = (f: string, re: RegExp) => lines(join(dirs.ours, f)).filter((l) => re.test(l)).length;
    console.log(
      `B. King quail: hap_split and unloc run on both files, ${OUTPUTS.length} outputs (${rows} lines) compared. ` +
      `From OpenPretext's file: ${count('Hap_1/hap.unlocs.no_hapdups.agp', /_unloc_\d+\t/)} + ` +
      `${count('Hap_2/hap.unlocs.no_hapdups.agp', /_unloc_\d+\t/)} unloc rows renamed, ` +
      `${count('Hap_1/hap1.agp', /\tW\t/)} / ${count('Hap_2/hap2.agp', /\tW\t/)} sequence rows in haplotype 1 / 2.`);
  } else {
    console.log('B. skipped: the quail files are not in test-data/case-study/quail');
  }

  if (failures.length > 0) {
    for (const f of failures) console.log(`FAIL  ${f}`);
    console.log(`Output kept in ${out}`);
    process.exit(1);
  }
  rmSync(out, { recursive: true, force: true });
  console.log(ran === 0 ? 'Nothing to run.' : 'The VGP scripts give the same output from OpenPretext\'s AGP as from PretextView\'s.');
  process.exit(ran === 0 ? 2 : 0);
}

main();
