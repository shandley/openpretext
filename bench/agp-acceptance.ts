/**
 * Acceptance test of AGP export against the tool that consumes it.
 *
 * Sanger Tree of Life turns a PretextView AGP into the curated assembly with
 * `pretext-to-asm` (https://github.com/sanger-tol/agp-tpf-utils, MIT). Its
 * repository ships 14 real curations: the pre-curation assembly, the AGP
 * PretextView wrote, and the files `pretext-to-asm` is expected to produce.
 *
 * For each, this script
 *   1. reads the PretextView AGP into OpenPretext's model (the importer),
 *   2. writes it back out with OpenPretext's AGP writer,
 *   3. runs `pretext-to-asm` on OpenPretext's file,
 *   4. compares every output file with the expected one from the repository.
 *
 * A pass means the Sanger tool builds the same curated assembly from our AGP
 * as from PretextView's. The tool's log file quotes the AGP's header, which
 * names the program that wrote it, so that one line is set aside.
 *
 * Setup (once; test-data/ is not committed):
 *   git clone https://github.com/sanger-tol/agp-tpf-utils test-data/agp-tpf-utils
 *   cd test-data/agp-tpf-utils && uv venv .venv && uv pip install --python .venv/bin/python -e .
 * Run:
 *   npx tsx bench/agp-acceptance.ts [--keep]
 */

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseAGP, planAGPImport } from '../src/formats/AGPParser';
import { buildAGPObjects } from '../src/export/AGPModel';
import { buildAGPRows, formatAGPRow, generateAGPHeader } from '../src/export/AGPWriter';
import { mapFromAGP, FILLER } from '../tests/helpers/agpFixtureMap';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = join(ROOT, 'test-data/agp-tpf-utils');
const DATA = join(REPO, 'tests/data');
const TOOL = join(REPO, '.venv/bin/pretext-to-asm');

/** The fixture's AGP, read into our model and written back by our writer. */
function rewrite(agpText: string): string {
  const parsed = parseAGP(agpText);
  const map = mapFromAGP(parsed);
  const plan = planAGPImport(parsed, map);
  const contigs = plan.contigs.map((c) => ({ ...c }));
  plan.scaffolds.forEach((sc, k) => { for (const id of sc.contigIds) contigs[id].scaffoldId = k + 1; });
  const tags = new Map(plan.tags);
  const objects = buildAGPObjects({ ...map, contigs }, plan.contigOrder)
    // The sequence standing in for texels the fixture does not account for.
    .filter((o) => o.fragments.every((f) => f.component !== FILLER));
  const rows = buildAGPRows(objects, { tagsOf: (id) => tags.get(id) ?? [] }, 'pretextview').map(formatAGPRow);
  return [generateAGPHeader(map, 'pretextview'), ...rows].join('\n') + '\n';
}

/** Lines of a tool log that quote the AGP header's program name. */
const quotesProgram = (line: string) => /Generated by (PretextView|OpenPretext)/.test(line);

function main(): void {
  if (!existsSync(TOOL) || !existsSync(DATA)) {
    console.error(`pretext-to-asm is not set up under ${REPO}. See the setup lines at the top of this file.`);
    process.exit(2);
  }
  const keep = process.argv.includes('--keep');
  const out = mkdtempSync(join(ROOT, 'test-data/agp-acceptance-'));
  let failed = 0;

  for (const dir of readdirSync(DATA).sort()) {
    const specimenDir = join(DATA, dir);
    if (!statSync(specimenDir).isDirectory()) continue;
    // Directory names such as ilLyoCler1_2 carry an assembly version.
    const m = /^(.*)_(\d+)$/.exec(dir);
    const specimen = m ? m[1] : dir;
    const version = m ? `.${m[2]}` : '';
    const inputTpf = `${specimen}-input${version}.tpf`;
    const pretextAgp = `${specimen}-pretext${version}.agp`;
    if (!existsSync(join(specimenDir, pretextAgp))) continue;

    const work = join(out, dir);
    mkdirSync(work, { recursive: true });
    const ours = join(work, `${specimen}-openpretext${version}.agp`);
    writeFileSync(ours, rewrite(readFileSync(join(specimenDir, pretextAgp), 'utf8')));

    const problems: string[] = [];
    try {
      execFileSync(TOOL, [
        '--assembly', join(specimenDir, inputTpf),
        '--pretext', ours,
        '--output', join(work, `${specimen}-pretext-to-tpf${version}.tpf`),
        '--write-log',
      ], { stdio: ['ignore', 'pipe', 'pipe'] });
    } catch (e) {
      const err = e as { stderr?: Buffer; message: string };
      problems.push(`pretext-to-asm failed: ${(err.stderr?.toString() ?? err.message).trim().split('\n').slice(-3).join(' | ')}`);
    }

    if (problems.length === 0) {
      for (const file of readdirSync(specimenDir).sort()) {
        if (file === inputTpf || file === pretextAgp || file.startsWith('.')) continue;
        const produced = join(work, file);
        if (!existsSync(produced)) { problems.push(`${file}: not produced`); continue; }
        const want = readFileSync(join(specimenDir, file), 'utf8').split('\n').filter((l) => !quotesProgram(l));
        const got = readFileSync(produced, 'utf8').split('\n').filter((l) => !quotesProgram(l));
        // The log names its input file; ours has a different name.
        const same = (a: string, b: string) => a === b ||
          a.replace(`${specimen}-pretext${version}.agp`, '') === b.replace(`${specimen}-openpretext${version}.agp`, '').replace(work, specimenDir);
        const firstDiff = want.findIndex((l, i) => !same(l, got[i] ?? ''));
        if (want.length !== got.length || firstDiff !== -1) {
          const i = firstDiff === -1 ? Math.min(want.length, got.length) : firstDiff;
          problems.push(`${file}: differs at line ${i + 1}\n      expected: ${want[i]}\n      produced: ${got[i]}`);
        }
      }
    }

    if (problems.length === 0) {
      console.log(`ok    ${dir}`);
    } else {
      failed++;
      console.log(`FAIL  ${dir}`);
      for (const p of problems) console.log(`    ${p}`);
    }
  }

  if (!keep && failed === 0) rmSync(out, { recursive: true, force: true });
  else console.log(`Output kept in ${out}`);
  console.log(failed === 0 ? 'All specimens pass.' : `${failed} specimen(s) failed.`);
  process.exit(failed === 0 ? 0 : 1);
}

main();
