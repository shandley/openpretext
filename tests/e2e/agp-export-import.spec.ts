/**
 * AGP export and import in the running app: the file a curator hands to the
 * next tool, and reading one back.
 *
 * The map is the synthetic one (1024 texels, 1,024,000 bp, so 1000 bp per
 * texel) with contigs a1..a5 of 200, 300, 124, 250 and 150 texels.
 */

import { test, expect, type Page } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { buildSyntheticPretext, patternTexel } from '../helpers/pretextWriter';
import { validateAGP } from '../helpers/agpValidate';

const FILE = Buffer.from(buildSyntheticPretext({
  textureResLog2: 8, tilesLog2: 2, mipMapLevels: 2,
  contigs: [200, 300, 124, 250, 150].map((texels, i) => ({ name: `a${i + 1}`, texels })),
  texel: patternTexel,
}));

async function load(page: Page): Promise<void> {
  await page.goto('/');
  await page.locator('#file-input').setInputFiles({ name: 'm.pretext', mimeType: 'application/octet-stream', buffer: FILE });
  await expect(page.locator('#welcome')).toBeHidden({ timeout: 30_000 });
  await expect(page.locator('#status-contigs')).toHaveText('5 contigs');
}

async function download(page: Page, buttonId: string): Promise<{ name: string; text: string }> {
  const [d] = await Promise.all([
    page.waitForEvent('download'),
    page.evaluate((id) => (document.getElementById(id) as HTMLButtonElement).click(), buttonId),
  ]);
  return { name: d.suggestedFilename(), text: readFileSync(await d.path(), 'utf8') };
}

const dataRows = (text: string) => text.split('\n').filter((l) => l && !l.startsWith('#'));

test.use({ viewport: { width: 1280, height: 720 }, deviceScaleFactor: 1 });

test('a curation exports as the AGP PretextView would write, and reads back', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await load(page);

  // Cut a2, turn the right piece round, paint a1 with both pieces, tag and exclude.
  await page.evaluate(() => {
    const { ctx, state, CurationEngine, metaTags, contigExclusion } = (window as any).__openpretext;
    CurationEngine.cut(1, 120);
    CurationEngine.invert(2);
    const sc = ctx.scaffoldManager.createScaffold('chrZ');
    ctx.scaffoldManager.paintContigs([0, 1, 2], sc);
    const order = state.get().contigOrder;
    metaTags.addTag(order[0], 'Z');
    metaTags.addTag(order[0], 'Hap_1');
    metaTags.addTag(order[2], 'Unloc');
    contigExclusion.toggle(order[4]);      // a4, excluded with no reason given yet
  });

  // The pipeline file is refused until the excluded contig says why.
  await page.evaluate(() => (document.getElementById('btn-save-agp') as HTMLButtonElement).click());
  await expect(page.locator('.toast').filter({ hasText: /AGP not exported\. 1 excluded contig has no tag saying why it is removed: "a4"/ }))
    .toBeVisible({ timeout: 5_000 });
  await page.evaluate(() => {
    const { state, metaTags } = (window as any).__openpretext;
    metaTags.addTag(state.get().contigOrder[4], 'Contaminant');
  });

  const agp = await download(page, 'btn-save-agp');
  expect(agp.name).toBe('m.agp');
  expect(agp.text.split('\n').slice(0, 3)).toEqual([
    '##agp-version\t2.1',
    expect.stringMatching(/^# DESCRIPTION: Generated by OpenPretext Version \d+\.\d+\.\d+$/),
    '# HiC MAP RESOLUTION: 1000.000000 bp/texel',
  ]);
  expect(dataRows(agp.text).map((l) => l.replace(/\t/g, ' '))).toEqual([
    'Scaffold_1 1 200000 1 W a1 1 200000 + Painted Z Hap_1',
    'Scaffold_1 200001 200100 2 U 100 scaffold yes proximity_ligation',
    'Scaffold_1 200101 320100 3 W a2 1 120000 + Painted',
    'Scaffold_1 320101 320200 4 U 100 scaffold yes proximity_ligation',
    'Scaffold_1 320201 500200 5 W a2 120001 300000 - Painted Unloc',
    'Scaffold_2 1 124000 1 W a3 1 124000 +',
    'Scaffold_3 1 250000 1 W a4 1 250000 + Contaminant',
    'Scaffold_4 1 150000 1 W a5 1 150000 +',
  ]);
  expect(validateAGP(agp.text)).toEqual([]);

  // The standard file: nine columns, the excluded contig left out.
  const standard = await download(page, 'btn-save-agp-standard');
  expect(standard.name).toBe('m.standard.agp');
  expect(validateAGP(standard.text, { maxColumns: 9 })).toEqual([]);
  expect(standard.text).not.toMatch(/\ta4\t/);
  expect(standard.text.split('\n')[0]).toBe('##agp-version 2.1');

  // Read the pipeline file back onto a freshly loaded map.
  await load(page);
  await page.locator('#agp-file-input').setInputFiles({ name: 'm.agp', mimeType: 'text/plain', buffer: Buffer.from(agp.text) });
  await expect(page.locator('.toast').filter({ hasText: 'AGP applied: 6 rows, 1 cut, 1 scaffold, 3 tagged contigs' }))
    .toBeVisible({ timeout: 10_000 });
  await expect(page.locator('#status-contigs')).toHaveText('6 contigs');
  const restored = await page.evaluate(() => {
    const { ctx, state, metaTags } = (window as any).__openpretext;
    const s = state.get();
    const scaffoldName = (id: number | null) => ctx.scaffoldManager.getAllScaffolds().find((x: any) => x.id === id)?.name ?? null;
    return {
      undo: s.undoStack.length,
      shown: s.contigOrder.map((id: number) => {
        const c = s.map.contigs[id];
        return [c.name, c.pixelStart, c.pixelEnd, c.inverted, scaffoldName(c.scaffoldId), metaTags.getTags(id).join('+')];
      }),
    };
  });
  expect(restored.undo).toBe(0);
  expect(restored.shown).toEqual([
    ['a1', 0, 200, false, 'Scaffold_1', 'Z+Hap_1'],
    ['a2_1', 200, 320, false, 'Scaffold_1', ''],
    ['a2_2', 320, 500, true, 'Scaffold_1', 'Unloc'],
    ['a3', 500, 624, false, null, ''],
    ['a4', 624, 874, false, null, 'Contaminant'],
    ['a5', 874, 1024, false, null, ''],
  ]);

  // And it exports the same rows again.
  const again = await download(page, 'btn-save-agp');
  expect(dataRows(again.text)).toEqual(dataRows(agp.text));

  // An AGP for another assembly is refused and changes nothing.
  await page.locator('#agp-file-input').setInputFiles({
    name: 'other.agp', mimeType: 'text/plain',
    buffer: Buffer.from('##agp-version\t2.1\nScaffold_1\t1\t100\t1\tW\tchrX\t1\t100\t+\n'),
  });
  await expect(page.locator('.toast').filter({ hasText: /This AGP cannot be applied: none of its sequences are in the loaded map/ }))
    .toBeVisible({ timeout: 5_000 });
  await expect(page.locator('#status-contigs')).toHaveText('6 contigs');

  expect(errors).toEqual([]);
});
