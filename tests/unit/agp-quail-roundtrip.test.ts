/**
 * A released Sanger curation, read and written back.
 *
 * test-data/case-study/quail holds the king quail map and the AGP PretextView
 * 0.2.5 wrote from the curator's session. Importing that AGP onto the map and
 * exporting again must give the same rows: same objects, coordinates, gaps,
 * orientations and tags. That exercises the importer, the row model and the
 * writer against a file none of them was written from.
 *
 * Skipped where the files are absent (too large to commit).
 */

import { describe, it, expect } from 'vitest';
import { existsSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { readPretextHeader } from '../../src/formats/PretextParser';
import { parseAGP, planAGPImport } from '../../src/formats/AGPParser';
import { buildAGPObjects, checkTiling } from '../../src/export/AGPModel';
import { buildAGPRows, formatAGPRow, generateAGPHeader } from '../../src/export/AGPWriter';
import type { MapData } from '../../src/core/State';

const DIR = resolve(__dirname, '../../test-data/case-study/quail');
const MAP = resolve(DIR, 'bCotChi1.combined.pretext');
const AGP = resolve(DIR, 'bCotChi1.combined.pretext.20240422.agp');
const d = existsSync(MAP) && existsSync(AGP) ? describe : describe.skip;

function loadMap(): MapData {
  const bytes = readFileSync(MAP);
  const { header, contigs } = readPretextHeader(
    bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength) as ArrayBuffer);
  return {
    filename: 'bCotChi1.combined.pretext',
    textureSize: header.numberOfPixels1D,
    numMipMaps: header.mipMapLevels,
    tileResolution: header.textureResolution,
    tilesPerDimension: header.numberOfTextures1D,
    contigs: contigs.map((c, i) => ({
      name: c.name, originalIndex: i, length: c.length,
      pixelStart: c.pixelStart, pixelEnd: c.pixelEnd, inverted: false, scaffoldId: null,
    })),
    fileContigCount: contigs.length,
    genomeLength: Number(header.totalGenomeLength),
    contactMap: null, rawTiles: null, parsedHeader: header, extensions: new Map(),
  } as unknown as MapData;
}

d('king quail: PretextView AGP in, the same AGP out', () => {
  const text = readFileSync(AGP, 'utf8');
  const original = text.split('\n').filter((l) => l !== '');

  it('reads the file without complaint', () => {
    const parsed = parseAGP(text);
    expect(parsed.skippedLines).toEqual([]);
    expect(parsed.resolution).toBeCloseTo(59245.052002, 6);
    expect(parsed.hasExtraColumns).toBe(true);
    expect(parsed.rows).toHaveLength(513);

    const plan = planAGPImport(parsed, loadMap());
    // Every coordinate in the file is on a texel boundary of this map.
    expect(plan.warnings.filter((w) => /texel boundary/.test(w))).toEqual([]);
    expect(plan.stats.rows).toBe(513);
    expect(plan.stats.scaffolds).toBe(new Set(original.filter((l) => /\tPainted/.test(l)).map((l) => l.split('\t')[0])).size);
  });

  it('writes back the rows it read', () => {
    const map = loadMap();
    const plan = planAGPImport(parseAGP(text), map);

    // Apply the plan as the app does: contigs, order, scaffold paint, tags.
    const contigs = plan.contigs.map((c) => ({ ...c }));
    plan.scaffolds.forEach((sc, k) => { for (const id of sc.contigIds) contigs[id].scaffoldId = k + 1; });
    const curated = { ...map, contigs };
    const tags = new Map(plan.tags);

    const objects = buildAGPObjects(curated, plan.contigOrder);
    expect(checkTiling(objects)).toEqual([]);
    const written = buildAGPRows(objects, { tagsOf: (id) => tags.get(id) ?? [] }, 'pretextview').map(formatAGPRow);

    // The original, less what PretextView's writer does not itself produce
    // (a stray tab after the tags), and with the header set aside.
    const expected = original.filter((l) => !l.startsWith('#')).map((l) => l.replace(/\t+$/, ''));
    expect(written.length).toBe(expected.length);
    const differing = written
      .map((w, i) => (w === expected[i] ? null : `${i + 1}: wrote ${JSON.stringify(w)}, file has ${JSON.stringify(expected[i])}`))
      .filter((x) => x !== null);
    expect(differing.slice(0, 10)).toEqual([]);
    expect(differing).toHaveLength(0);
  });

  it('writes the resolution line PretextView wrote', () => {
    const header = generateAGPHeader(loadMap(), 'pretextview').split('\n');
    expect(header[0]).toBe(original[0]);
    expect(header[2]).toBe(original[2]);
    expect(header[1]).toMatch(/^# DESCRIPTION: Generated by OpenPretext Version \d+\.\d+\.\d+$/);
  });
});
