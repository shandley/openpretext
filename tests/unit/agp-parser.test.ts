/**
 * Reading an AGP onto a loaded map: PretextView's layout (cuts as intervals,
 * Painted, tags) and plain nine-column AGP.
 *
 * Maps are 100 texels over 1,000,000 bp, so a texel is 10,000 bp.
 */

