const LAYOUT: Array<[string, number, number]> = [
  ['a', 0, 10], ['b', 10, 30], ['c', 30, 35], ['tiny', 35, 35], ['d', 35, 100],
];

function makeMap(layout = LAYOUT, genomeLength = 1_000_000): MapData {
  const N = layout[layout.length - 1][2];
  const contigs: ContigInfo[] = layout.map(([name, s, e], i) => ({
    name, originalIndex: i, length: Math.round(((e - s) / N) * genomeLength),
    pixelStart: s, pixelEnd: e, inverted: false, scaffoldId: null,
  }));
  return {
    filename: 'm.pretext', textureSize: N, numMipMaps: 1, tileResolution: N, tilesPerDimension: 1,
    contigs, fileContigCount: contigs.length, genomeLength,
    contactMap: null, rawTiles: null, parsedHeader: null, extensions: new Map(),
  };
}

const HEAD = '##agp-version\t2.1\n# DESCRIPTION: Generated by PretextView Version 0.2.5\n# HiC MAP RESOLUTION: 10000.000000 bp/texel\n';
const GAP = (obj: string, beg: number, part: number) => `${obj}\t${beg}\t${beg + 99}\t${part}\tU\t100\tscaffold\tyes\tproximity_ligation`;
const agp = (...rows: string[]) => HEAD + rows.map((r) => r.replace(/ /g, '\t')).join('\n') + '\n';

/** What a plan shows, left to right: name, texel span(s), orientation, scaffold, tags. */
function shown(plan: AGPImportPlan) {
  const scaffoldOf = new Map<number, string>();
  for (const sc of plan.scaffolds) for (const id of sc.contigIds) scaffoldOf.set(id, sc.name);
  const tags = new Map(plan.tags);
  return plan.contigOrder.map((id) => {
    const c = plan.contigs[id];
    const spans = c.pixelSegments
      ? c.pixelSegments.map((p) => `${p.start}-${p.end}${p.reversed ? 'r' : ''}`).join(',')
      : `${c.pixelStart}-${c.pixelEnd}${c.inverted ? 'r' : ''}`;
    return [c.name, spans, scaffoldOf.get(id) ?? null, (tags.get(id) ?? []).join('+')].join(' | ');
  });
}

/** Write a plan back out as AGP rows, the way the app would after applying it. */
function reexport(map: MapData, plan: AGPImportPlan, flavor: 'pretextview' | 'standard' = 'pretextview'): string[] {
  const contigs = plan.contigs.map((c) => ({ ...c }));
  plan.scaffolds.forEach((sc, k) => { for (const id of sc.contigIds) contigs[id].scaffoldId = k + 1; });
  const tags = new Map(plan.tags);
  const objects = buildAGPObjects({ ...map, contigs }, plan.contigOrder);
  return buildAGPRows(objects, { tagsOf: (id) => tags.get(id) ?? [] }, flavor).map(formatAGPRow);
}

describe('parseAGP', () => {
  it('reads sequence rows, the resolution, Painted and tags, and drops gap rows', () => {
    const parsed = parseAGP(agp(
      'Scaffold_1 1 100000 1 W a 1 100000 + Painted Z Hap_2',
      GAP('Scaffold_1', 100001, 2),
      'Scaffold_1 100101 300100 3 W b 1 200000 - Painted',
      'Scaffold_2 1 50000 1 W c 1 50000 + Haplotig',
    ));
    expect(parsed.resolution).toBe(10000);
    expect(parsed.hasExtraColumns).toBe(true);
    expect(parsed.skippedLines).toEqual([]);
    expect(parsed.rows).toEqual([
      { object: 'Scaffold_1', component: 'a', beg: 1, end: 100000, reversed: false, painted: true, tags: ['Z', 'Hap_2'], line: 4 },
      { object: 'Scaffold_1', component: 'b', beg: 1, end: 200000, reversed: true, painted: true, tags: [], line: 6 },
      { object: 'Scaffold_2', component: 'c', beg: 1, end: 50000, reversed: false, painted: false, tags: ['Haplotig'], line: 7 },
    ]);
  });

  it('copes with what real files contain: stray tabs, CRLF, blank lines, N gaps', () => {
    const text = '##agp-version\t2.1\r\n\r\n' +
      'Scaffold_1\t1\t100000\t1\tW\ta\t1\t100000\t+\tPainted\tHap_1\t\r\n' +
      'Scaffold_1\t100001\t100200\t2\tN\t200\tscaffold\tyes\tproximity_ligation\r\n' +
      'Scaffold_1\t100201\t300200\t3\tW\tb\t1\t200000\t+\tPainted\t\t\r\n';
    const parsed = parseAGP(text);
    expect(parsed.rows.map((r) => [r.component, r.painted, r.tags])).toEqual([['a', true, ['Hap_1']], ['b', true, []]]);
    expect(parsed.resolution).toBeNull();
    expect(parsed.skippedLines).toEqual([]);
  });

  it('reports lines it could not use instead of guessing', () => {
    const parsed = parseAGP(agp(
      'Scaffold_1 1 100000 1 W a 1 100000 +',
      'Scaffold_2 1 100 1 W b',                       // too few columns
      'Scaffold_3 1 100 1 W c 50 10 +',               // end before start
      'Scaffold_4 1 100 1 W d 1 x +',                 // not a number
      'Scaffold_5 1 100 1 W d 1 100 sideways',        // not an orientation
    ));
    expect(parsed.rows).toHaveLength(1);
    expect(parsed.skippedLines).toEqual([5, 6, 7, 8]);
  });

  it('reads plain nine-column AGP', () => {
    const parsed = parseAGP('scaffold_1\t1\t100\t1\tW\ta\t1\t100\t+\n');
    expect(parsed.hasExtraColumns).toBe(false);
    expect(parsed.rows[0].painted).toBe(false);
  });
});

describe('planAGPImport', () => {
  const map = makeMap();

  it('places whole sequences, in the file\'s order, and keeps what it does not mention', () => {
    const plan = planAGPImport(parseAGP(agp(
      'Scaffold_1 1 650000 1 W d 1 650000 +',
      'Scaffold_2 1 100000 1 W a 1 100000 +',
    )), map);
    expect(shown(plan)).toEqual([
      'd | 35-100 |  | ', 'a | 0-10 |  | ', 'b | 10-30 |  | ', 'c | 30-35 |  | ', 'tiny | 35-35 |  | ',
    ].map((s) => s.replace(' |  | ', ' |  | ')));
    expect(plan.warnings).toEqual(['2 sequences on the map are not in the AGP and were put at the end.']);
    expect(plan.stats).toEqual({ rows: 2, cuts: 0, scaffolds: 0, tagged: 0 });
  });

  it('makes the cuts the intervals call for', () => {
    const plan = planAGPImport(parseAGP(agp(
      'Scaffold_1 1 100000 1 W a 1 100000 +',
      'Scaffold_2 1 150000 1 W b 50001 200000 -',
      'Scaffold_3 1 50000 1 W b 1 50000 +',
      'Scaffold_4 1 50000 1 W c 1 50000 +',
      'Scaffold_5 1 650000 1 W d 1 650000 +',
    )), map);
    expect(shown(plan)).toEqual([
      'a | 0-10 |  | ', 'b_2 | 15-30r |  | ', 'b_1 | 10-15 |  | ', 'c | 30-35 |  | ', 'd | 35-100 |  | ', 'tiny | 35-35 |  | ',
    ]);
    expect(plan.stats.cuts).toBe(1);
    expect(plan.warnings).toEqual([]);
    // The pieces say which bases they are, for FASTA export.
    const piece = plan.contigs[plan.contigOrder[1]];
    expect(piece.sequenceSegments).toEqual([{ sourceName: 'b', start: 50000, end: 200000, revComp: true }]);
    expect(piece.length).toBe(150000);
    expect(piece.originalIndex).toBe(1);
  });

  it('paints the objects that carry Painted, names scaffolds after them, and reads tags per contig', () => {
    const plan = planAGPImport(parseAGP(agp(
      'Scaffold_1 1 100000 1 W a 1 100000 + Painted Z Hap_2',
      GAP('Scaffold_1', 100001, 2),
      'Scaffold_1 100101 300100 3 W b 1 200000 - Painted Unloc',
      'Scaffold_2 1 50000 1 W c 1 50000 + Painted',
      'Scaffold_3 1 650000 1 W d 1 650000 + Haplotig',
    )), map);
    expect(shown(plan)).toEqual([
      'a | 0-10 | Scaffold_1 | Z+Hap_2',
      'b | 10-30r | Scaffold_1 | Unloc',
      'c | 30-35 | Scaffold_2 | ',
      'd | 35-100 |  | Haplotig',
      'tiny | 35-35 |  | ',
    ]);
    expect(plan.stats).toEqual({ rows: 4, cuts: 0, scaffolds: 2, tagged: 3 });
  });

  it('reads an unpainted object of several rows as one joined contig', () => {
    const plan = planAGPImport(parseAGP(agp(
      'Scaffold_1 1 50000 1 W c 1 50000 - Contaminant',
      GAP('Scaffold_1', 50001, 2),
      'Scaffold_1 50101 150100 3 W a 1 100000 + Contaminant',
      'Scaffold_2 1 200000 1 W b 1 200000 +',
      'Scaffold_3 1 650000 1 W d 1 650000 +',
    )), map);
    expect(shown(plan)).toEqual([
      'c+a | 30-35r,0-10 |  | Contaminant', 'b | 10-30 |  | ', 'd | 35-100 |  | ', 'tiny | 35-35 |  | ',
    ]);
    const joined = plan.contigs[plan.contigOrder[0]];
    expect(joined.pixelEnd - joined.pixelStart).toBe(15);
    expect(joined.length).toBe(150000);
    expect(joined.sequenceSegments).toEqual([
      { sourceName: 'c', start: 0, end: 50000, revComp: true },
      { sourceName: 'a', start: 0, end: 100000, revComp: false },
    ]);
  });

  it('in plain nine-column AGP, takes an object of several parts as a scaffold', () => {
    const text = [
      'chr1\t1\t100000\t1\tW\ta\t1\t100000\t+',
      'chr1\t100001\t100200\t2\tN\t200\tscaffold\tyes\tproximity_ligation',
      'chr1\t100201\t300200\t3\tW\tb\t1\t200000\t-',
      'unplaced_0\t1\t50000\t1\tW\tc\t1\t50000\t+',
    ].join('\n');
    const plan = planAGPImport(parseAGP(text), map);
    expect(shown(plan).slice(0, 3)).toEqual(['a | 0-10 | chr1 | ', 'b | 10-30r | chr1 | ', 'c | 30-35 |  | ']);
  });

  it('takes a sequence named on one row whole, whatever its end coordinate (a corrected AGP)', () => {
    const plan = planAGPImport(parseAGP(agp('Scaffold_1 1 203417 1 W b 1 203417 +')), map);
    expect(shown(plan)[0]).toBe('b | 10-30 |  | ');
    expect(plan.warnings.filter((w) => /texel boundary/.test(w))).toEqual([]);
  });

  it('moves coordinates that are off the texel grid to the nearest boundary, and says so', () => {
    const plan = planAGPImport(parseAGP(agp(
      'Scaffold_1 1 52000 1 W b 1 52000 +',
      'Scaffold_2 1 151417 1 W b 52001 203417 +',
    )), map);
    expect(shown(plan).slice(0, 2)).toEqual(['b_1 | 10-15 |  | ', 'b_2 | 15-30 |  | ']);
    expect(plan.warnings[0]).toMatch(/^2 rows had coordinates that are not on a texel boundary of this map/);
  });

  it('keeps the part of a sequence the AGP leaves out, at the end, and says so', () => {
    const plan = planAGPImport(parseAGP(agp(
      'Scaffold_1 1 50000 1 W b 50001 100000 +',
      'Scaffold_2 1 100000 1 W a 1 100000 +',
    )), map);
    expect(shown(plan)).toEqual([
      'b_2 | 15-20 |  | ', 'a | 0-10 |  | ',
      'b_unplaced_0 | 10-15 |  | ', 'b_unplaced_10 | 20-30 |  | ',
      'c | 30-35 |  | ', 'tiny | 35-35 |  | ', 'd | 35-100 |  | ',
    ]);
    expect(plan.warnings).toContain('2 parts of sequences the AGP places only partly were kept and put at the end.');
  });

  it('always shows every texel of the map exactly once', () => {
    const texts = [
      agp('Scaffold_1 1 650000 1 W d 1 650000 -'),
      agp('Scaffold_1 1 50000 1 W b 50001 100000 +', 'Scaffold_2 1 100000 1 W d 300001 400000 -'),
      agp('Scaffold_1 1 100000 1 W a 1 100000 + Painted', GAP('Scaffold_1', 100001, 2), 'Scaffold_1 100101 150100 3 W d 1 50000 - Painted'),
    ];
    for (const text of texts) {
      const plan = planAGPImport(parseAGP(text), map);
      const runs = buildDisplayRuns(plan.contigs, plan.contigOrder);
      const texels = Array.from({ length: displayWidth(runs) }, (_, x) => displayToFileTexel(runs, x));
      expect([...texels].sort((x, y) => x - y)).toEqual(Array.from({ length: 100 }, (_, t) => t));
    }
  });

  it('ignores words that cannot be tags, and says which', () => {
    const plan = planAGPImport(parseAGP(agp('Scaffold_1 1 100000 1 W a 1 100000 + Painted Z not-a-tag')), map);
    expect(plan.tags).toEqual([[0, ['Z']]]);
    expect(plan.warnings.join(' ')).toMatch(/not usable as tags and were ignored: "not-a-tag"/);
  });

  it('skips sequences the map does not have, and says which', () => {
    const plan = planAGPImport(parseAGP(agp(
      'Scaffold_1 1 100000 1 W a 1 100000 +',
      'Scaffold_2 1 100 1 W ghost 1 100 +',
    )), map);
    expect(shown(plan)[0]).toBe('a | 0-10 |  | ');
    expect(plan.warnings[0]).toBe('1 sequence named in the AGP is not in the loaded map and was skipped: "ghost".');
  });

  describe('refuses, changing nothing', () => {
    const refused = (text: string, why: RegExp) => {
      let err: unknown;
      try { planAGPImport(parseAGP(text), map); } catch (e) { err = e; }
      expect(err).toBeInstanceOf(AGPImportError);
      expect((err as Error).message).toMatch(why);
    };

    it('an AGP for another assembly', () => {
      refused(agp('Scaffold_1 1 100 1 W chrX 1 100 +', 'Scaffold_2 1 100 1 W chrY 1 100 +'),
        /none of its sequences are in the loaded map \(for example "chrX", "chrY"\)/);
    });

    it('an AGP written for a map of another resolution', () => {
      refused(agp('Scaffold_1 1 100000 1 W a 1 100000 +').replace('10000.000000', '59245.052002'),
        /written for a map of 59245.052002 bp per texel, and the loaded map has 10000.000000/);
    });

    it('rows that overlap on one sequence', () => {
      refused(agp('Scaffold_1 1 100000 1 W b 1 100000 +', 'Scaffold_2 1 150000 1 W b 50001 200000 +'),
        /line 5: b 50001-200000 overlaps another row for the same sequence/);
    });

    it('a row smaller than a texel', () => {
      refused(agp('Scaffold_1 1 100 1 W b 1 100 +', 'Scaffold_2 1 199900 1 W b 101 200000 +'),
        /line 4: b 1-100 is smaller than one texel of this map/);
    });

    it('a file with no sequence rows', () => {
      refused('##agp-version 2.1\n', /no sequence rows/);
    });
  });
});

describe('export, then import, then export again', () => {
  let scaffolds: ScaffoldManager;

  function mulberry32(seed: number): () => number {
    let a = seed >>> 0;
    return () => {
      a = (a + 0x6d2b79f5) >>> 0;
      let t = a;
      t = Math.imul(t ^ (t >>> 15), t | 1);
      t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }

  beforeEach(() => {
    state.reset();
    metaTags.clearAll();
    contigExclusion.clearAll();
    scaffolds = new ScaffoldManager();
    CurationEngine.setScaffoldManager(scaffolds);
  });

  it('gives the same file, for any curation', () => {
    const layout: Array<[string, number, number]> = [
      ['s1', 0, 37], ['s2', 37, 38], ['s3', 38, 38], ['s4', 38, 101], ['s5', 101, 180], ['s6', 180, 256],
    ];
    const TAGS = ['Haplotig', 'Unloc', 'Z', 'W', 'Hap_1', 'Hap_2', 'Contaminant', 'Target'];
    for (let seed = 1; seed <= 80; seed++) {
      state.reset();
      metaTags.clearAll();
      scaffolds = new ScaffoldManager();
      CurationEngine.setScaffoldManager(scaffolds);
      const map = makeMap(layout, 987_654_321);
      state.update({ map, contigOrder: layout.map((_, i) => i) });
      const rnd = mulberry32(seed);
      for (let k = 0; k < 20; k++) {
        const s = state.get();
        const count = s.contigOrder.length;
        const i = Math.floor(rnd() * count);
        const r = rnd();
        const c = s.map!.contigs[s.contigOrder[i]];
        const w = c.pixelEnd - c.pixelStart;
        if (r < 0.3) { if (w >= 2) CurationEngine.cut(i, 1 + Math.floor(rnd() * (w - 1))); }
        else if (r < 0.42) { if (i < count - 1 && !CurationEngine.joinBlockedReason(i)) CurationEngine.join(i); }
        else if (r < 0.6) CurationEngine.invert(i);
        else if (r < 0.78) CurationEngine.move(i, Math.floor(rnd() * count));
        else if (r < 0.9) {
          const id = scaffolds.createScaffold(undefined, { record: false });
          scaffolds.paintContigs([i, i + 1].filter((p) => p < count), id, { record: false });
        } else if (w > 0) metaTags.addTag(s.contigOrder[i], TAGS[Math.floor(rnd() * TAGS.length)]);
      }
      // Tags that would stop the export are not the subject here.
      const s = state.get();
      for (const id of s.contigOrder) {
        if (s.map!.contigs[id].scaffoldId === null) metaTags.removeTag(id, 'Unloc');
        for (const t of ['Z', 'W', 'Hap_1', 'Hap_2']) metaTags.removeTag(id, t);
      }

      const first = exportAGP(state.get());
      expect(validateAGP(first), `seed ${seed}`).toEqual([]);
      const plan = planAGPImport(parseAGP(first), makeMap(layout, 987_654_321));
      expect(plan.warnings.filter((w) => !/not in the AGP/.test(w)), `seed ${seed}`).toEqual([]);
      const second = reexport(makeMap(layout, 987_654_321), plan);
      expect(second, `seed ${seed}`).toEqual(first.split('\n').filter((l) => l && !l.startsWith('#')));
    }
  });
});

// The 14 real PretextView exports that Sanger's agp-tpf-utils tests with
// (MIT licence), when a checkout is present at test-data/agp-tpf-utils (see
// bench/agp-acceptance.ts). They come without maps, so the map is rebuilt
// from the file itself (tests/helpers/agpFixtureMap.ts).
const FIXTURES = resolve(__dirname, '../../test-data/agp-tpf-utils/tests/data');
const fixtureFiles = existsSync(FIXTURES)
  ? readdirSync(FIXTURES)
      .map((d) => resolve(FIXTURES, d, `${d}-pretext.agp`)).filter((f) => existsSync(f))
  : [];

(fixtureFiles.length > 0 ? describe : describe.skip)('real PretextView exports from agp-tpf-utils', () => {
  it.each(fixtureFiles)('%s reads and writes back unchanged', (file) => {
    const text = readFileSync(file, 'utf8');
    const parsed = parseAGP(text);
    expect(parsed.skippedLines).toEqual([]);
    expect(parsed.resolution).not.toBeNull();
    const map = mapFromAGP(parsed);

    const plan = planAGPImport(parsed, map);
    const written = reexport(map, plan).filter((l) => l.split('\t')[5] !== FILLER);
    const original = text.split('\n').filter((l) => l && !l.startsWith('#')).map((l) => l.replace(/\t+$/, ''));
    expect(written).toHaveLength(original.length);

    // Tags are compared as a set per row, because some of these files were
    // edited by hand after export and their tag order is not PretextView's.
    const norm = (l: string) => {
      const c = l.split('\t');
      return [...c.slice(0, 9), ...c.slice(9).sort()].join('\t');
    };
    const differing = written.map(norm)
      .map((w, i) => (w === norm(original[i]) ? null : `${i + 1}: wrote ${w} | file ${norm(original[i])}`))
      .filter((x) => x !== null);
    expect(differing.slice(0, 5)).toEqual([]);
  });
});
